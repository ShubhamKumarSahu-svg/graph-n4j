"""Synchronize release metadata and generate the changelog from git history."""

import argparse
import re
import subprocess
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def bump(kind: str) -> str:
    path = ROOT / "pyproject.toml"
    text = path.read_text()
    current = re.search(r'version = "(\d+\.\d+\.\d+)"', text).group(1)
    parts = list(map(int, current.split(".")))
    index = {"major": 0, "minor": 1, "patch": 2}[kind]
    parts[index] += 1
    parts[index + 1 :] = [0] * (2 - index)
    version = ".".join(map(str, parts))
    path.write_text(text.replace(f'version = "{current}"', f'version = "{version}"', 1))
    (ROOT / "graph_n4j/_version.py").write_text(f'__version__ = "{version}"\n')
    init = ROOT / "graph_n4j/__init__.py"
    init.write_text(
        re.sub(
            r'__version__ = "[^"]+"', "from graph_n4j._version import __version__", init.read_text()
        )
    )
    history = subprocess.check_output(["git", "log", "--format=%cs%x09%s"], cwd=ROOT, text=True)
    sections = [
        "# Changelog",
        "",
        "Generated by scripts/bump_version.py.",
        "",
        f"## [{version}] - {date.today()}",
        "",
    ]
    for entry in history.splitlines():
        day, subject = entry.split("\t", 1)
        release = re.search(r"chore\(release\):.*v(\d+\.\d+\.\d+)", subject)
        if release:
            sections.extend(["", f"## [{release.group(1)}] - {day}", ""])
        else:
            sections.append("- " + subject)
    (ROOT / "CHANGELOG.md").write_text("\n".join(sections) + "\n")
    subprocess.run(
        [
            "git",
            "add",
            "pyproject.toml",
            "graph_n4j/__init__.py",
            "graph_n4j/_version.py",
            "CHANGELOG.md",
        ],
        cwd=ROOT,
        check=True,
    )
    return version


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("kind", choices=["major", "minor", "patch"])
    print(bump(parser.parse_args().kind))
